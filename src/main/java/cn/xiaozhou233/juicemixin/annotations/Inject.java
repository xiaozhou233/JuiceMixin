package cn.xiaozhou233.juicemixin.annotations;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Repeatable;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a method as a mixin handler and describes where its code is injected
 * into the target class.
 * <p>
 * The injected location is addressed explicitly through {@link #method()} and
 * {@link #desc()}, so the handler's own name and signature do not have to match
 * the target method.
 * <p>
 * The annotation is repeatable: one handler may declare several {@code @Inject}
 * annotations. Two or more of them are wrapped by the compiler into the
 * generated {@link List} container.
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.METHOD)
@Repeatable(Inject.List.class)
public @interface Inject {

    /**
     * Name of the target method, exactly as it appears in the target class and
     * without its descriptor.
     *
     * @return the target method name
     */
    String method();

    /**
     * Descriptor of the target method, for example {@code "(ILjava/lang/String;)V"}.
     * Required, because the target method is resolved by name plus descriptor.
     * <p>
     * Note that this is the descriptor of the method being injected <b>into</b>,
     * not of the handler; {@link At#target()} describes the instruction matched
     * by the injection point.
     *
     * @return the target method descriptor
     */
    String desc();

    /**
     * Injection point. Defaults to a bare {@code @At}, i.e. {@code TAIL}.
     *
     * @return the injection point description
     */
    At at() default @At;

    /**
     * Container generated by the compiler to hold repeated {@link Inject}
     * annotations. Not intended to be used directly.
     * <p>
     * Since this nested type is itself called {@code List}, {@code java.util.List}
     * has to be referenced by its fully qualified name wherever it would
     * otherwise clash inside this file.
     */
    @Documented
    @Retention(RetentionPolicy.RUNTIME)
    @Target(ElementType.METHOD)
    @interface List {
        /**
         * The repeated {@link Inject} annotations, in declaration order.
         *
         * @return the repeated annotations
         */
        Inject[] value();
    }
}
